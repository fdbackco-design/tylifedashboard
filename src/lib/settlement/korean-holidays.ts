  '2026-02-17', // 설날 (음력 1월 1일)
  '2026-02-18', // 설날 연휴 (음력 1월 2일)
  '2026-03-01', // 3·1절
  '2026-03-02', // 3·1절 대체공휴일
  '2026-05-05', // 어린이날
  '2026-05-24', // 부처님오신날 (음력 4월 8일)
  '2026-05-25', // 부처님오신날 대체공휴일
  '2026-06-03', // 제9회 전국동시지방선거
  '2026-06-06', // 현충일
  '2026-08-15', // 광복절
  '2026-08-17', // 광복절 대체공휴일
  '2026-09-24', // 추석 연휴 전날 (음력 8월 14일)
