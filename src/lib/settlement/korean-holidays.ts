/**
 * 정산 v2 윈도우 보정용 한국 공휴일 데이터.
 *
 * 용도
 *   - 정산월별 해피콜 인정 시작/종료일(전월 26일~당월 25일)이 주말/공휴일일 때
 *     다음 영업일까지 인정하기 위한 보정 데이터.
 *
 * 데이터 범위
 *   - 연도별로 명시적으로 둔다. 새 연도가 시작되면 `KOREAN_HOLIDAYS_<year>` 를 추가하고
 *     `ALL_KOREAN_HOLIDAYS` 합집합에 넣는다.
 *   - 음력 기반 공휴일(설날, 추석, 부처님오신날 등)과 대체공휴일은 한국천문연구원
 *     「<year> 월력요항」을 기준으로 미리 환산해 둔다.
 *
 * 제외 항목
 *   - 근로자의 날(5/1): 관공서 공휴일이 아니고 대체공휴일 대상도 아님. 정산 기준일
 *     (25일·30일)에 영향이 없어 데이터에서 제외한다. 필요 시 회사 정책에 맞춰 추가.
 *
 * 출처
 *   - 2026: 한국천문연구원 「2026년 월력요항」 (대체공휴일 4회: 3/2, 5/25, 8/17, 10/5)
 */

